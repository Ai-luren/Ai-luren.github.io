import { createCoverStudio } from '../tools/cover-studio/server.mjs';
import { chromium } from 'playwright-core';
import { createSafePage } from './lib/safe-media.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

const root=path.resolve(import.meta.dirname,'..');
const fixture=await fs.mkdtemp(path.join(os.tmpdir(),'ailuren-cover-ux-'));
for(const p of ['src','assets/images','index.html','works.html'])await fs.cp(path.join(root,p),path.join(fixture,p),{recursive:true});
await fs.mkdir(path.join(fixture,'assets/videos'),{recursive:true});
await fs.symlink(path.join(root,'assets/videos/works'),path.join(fixture,'assets/videos/works'));
await fs.symlink(path.join(root,'node_modules'),path.join(fixture,'node_modules'));
await fs.writeFile(path.join(fixture,'package.json'),'{"type":"module"}');
const hash = async p=>createHash('sha256').update(await fs.readFile(p)).digest('hex');
const originalCover=path.join(root,'assets/images/project-covers/commercial/Watsons Brand Commercial.webp');
const hashBefore=await hash(originalCover);
let studio, browser;
try{
  studio=await createCoverStudio({projectRoot:fixture,port:5224});
  browser=await chromium.launch({executablePath:'/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',headless:true});
  const page=await createSafePage(browser,{viewport:{width:1440,height:920},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(studio.url); await page.locator('.ux-advanced-nav').evaluate(x=>x.open=true);
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('已载入'));
  await page.evaluate(()=>document.querySelector('[data-ux-advanced="manage"]').click());
  await page.screenshot({path:'/tmp/ailuren-cover-ux-manage.png'});
  const managedId=await page.locator('#managed-project').inputValue();
  assert(managedId);
  await page.locator('#start-cover-for-managed').click();
  assert.equal(await page.locator('#project-select').inputValue(),managedId);
  assert(await page.locator('#association-detail').isVisible());
  await page.locator('#project-select').selectOption('01');
  assert(await page.locator('#association-detail').isVisible());
  assert((await page.locator('#replace-target-status').textContent()).includes('精选'));
  assert.equal(await page.locator('#project-select option[value="01"]').isDisabled(),false);
  await page.screenshot({path:'/tmp/ailuren-cover-ux-target.png'});
  const imageFile=path.join(root,'assets/images/project-covers/commercial/Wireless Earbuds Lifestyle Ad.webp');
  await page.locator('#image-file').setInputFiles(imageFile);
  await page.waitForFunction(()=>!document.querySelector('#export-cover').disabled && document.querySelector('#frame-status').textContent.includes('导入图片'),null,{timeout:60000});
  await page.locator('#export-cover').click();
  await page.waitForFunction(()=>!document.querySelector('#cover-confirm').hidden,null,{timeout:60000});
  await page.locator('#compare-old-cover').evaluate(img=>img.decode());
  await page.locator('#compare-new-cover').evaluate(img=>img.decode());
  assert(await page.locator('#associate-cover').isDisabled());
  assert.equal(await page.locator('#compare-new-cover').evaluate(e=>e.naturalWidth),900);
  await page.screenshot({path:'/tmp/ailuren-cover-ux-confirm.png',fullPage:true});
  await page.locator('#replace-consent').check();
  assert(await page.locator('#associate-cover').isEnabled());
  await page.locator('#associate-cover').click();
  await page.waitForFunction(()=>!document.querySelector('#cover-confirm-result').hidden);
  const mapping=JSON.parse(await fs.readFile(path.join(fixture,'src/data/project-cover-overrides.json'),'utf8'));
  assert(mapping['01']);
  assert.equal(await hash(originalCover),hashBefore);
  assert.equal(await fs.stat(path.join(fixture,'assets/images/project-covers',mapping['01'])).then(x=>x.size>0),true);
  await page.locator('[data-workflow-target="order"]').click();
  await page.locator('#order-items .order-item[data-id="01"] .order-change-cover').click();
  assert.equal(await page.locator('#project-select').inputValue(),'01');
  await page.locator('[data-workflow-target="order"]').click();
  await page.locator('#order-items .order-thumb').first().evaluate(img=>img.decode());
  await page.screenshot({path:'/tmp/ailuren-cover-ux-order.png'});

  assert.deepEqual(errors,[]);
  console.log('COVER_UX_PASS: featured selection, comparison, confirmation, original preserved, navigation');
  console.log('FIXTURE',fixture);
}finally{
  if(browser)await browser.close();
  if(studio)await studio.close();
}
